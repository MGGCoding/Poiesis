// Builds supabase/seed.sql from muse-bank/index.json, so the database
// knows which works belong to which day (the gate checks this).
// Run it again after choosing a day's option in the muse bank.
//
//   node supabase/seed-from-muse-bank.mjs
//
// Then paste supabase/seed.sql into the Supabase SQL editor, or run
// `supabase db reset` locally. Safe to run again: it upserts.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const bank = JSON.parse(readFileSync(join(root, "muse-bank", "index.json"), "utf8"));

const q = (v) => (v == null ? "null" : "'" + String(v).replace(/'/g, "''") + "'");
const j = (o) => q(JSON.stringify(o)) + "::jsonb";

// Which works people write on each day.
//  - v1 days list them directly: poem, passage, painting.
//  - v2 days (from 30 Sept) offer four options A–D. The seed uses the
//    chosen option, or the suggested one until you choose. The third work
//    is that option's Scripture reading (Round 10); the painting sits
//    beside it as an image and is not written on.
const works = new Map(bank.works.map((w) => [w.id, w]));
const dayWorks = [];
for (const d of bank.days) {
  if (Array.isArray(d.works)) { dayWorks.push([d.date, d.theme || "", d.works]); continue; }
  const letter = d.chosen || d.suggested;
  const o = (d.options || []).find((x) => x.letter === letter);
  if (!o) { console.warn(`${d.date}: no chosen or suggested option; skipped`); continue; }
  const sid = `scripture-${d.date}`;
  works.set(sid, { id: sid, slot: "scripture", title: o.ref, maker: o.source || "",
    text: o.text, option: o.letter, painting: o.painting || null });
  dayWorks.push([d.date, o.theme || "", [o.poem, o.passage, sid]]);
}
for (const [date, , ids] of dayWorks) for (const id of ids)
  if (!works.has(id)) throw new Error(`${date}: work "${id}" is not in index.json`);

const lines = ["-- Generated by supabase/seed-from-muse-bank.mjs. Do not edit by hand.", "begin;", ""];

lines.push("insert into public.works (id, slot, title, maker, meta) values");
lines.push(
  [...works.values()]
    .map((w) => {
      const { id, slot, title, maker, ...meta } = w;
      return `  (${q(id)}, ${q(slot)}, ${q(title)}, ${q(maker || "")}, ${j(meta)})`;
    })
    .join(",\n") +
    "\non conflict (id) do update set slot = excluded.slot, title = excluded.title, maker = excluded.maker, meta = excluded.meta;",
);
lines.push("");

lines.push("insert into public.days (day, theme) values");
lines.push(
  dayWorks.map(([date, theme]) => `  (${q(date)}, ${q(theme)})`).join(",\n") +
    "\non conflict (day) do update set theme = excluded.theme;",
);
lines.push("");

lines.push("delete from public.day_works where day in (" + dayWorks.map(([date]) => q(date)).join(", ") + ");");
lines.push("insert into public.day_works (day, position, work_id) values");
lines.push(
  dayWorks.flatMap(([date, , ids]) => ids.map((w, i) => `  (${q(date)}, ${i + 1}, ${q(w)})`)).join(",\n") + ";",
);
lines.push("", "commit;", "");

const out = join(root, "supabase", "seed.sql");
writeFileSync(out, lines.join("\n"));
console.log(`Wrote ${out}: ${works.size} works, ${dayWorks.length} days.`);
